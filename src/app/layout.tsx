import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({ variable: "--font-geist-sans", subsets: ["latin"] });
const geistMono = Geist_Mono({ variable: "--font-geist-mono", subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Plants",
  description: "The landscape plant catalog: cultivars, albums and photographs.",
};

// Deliberately bare. This app was carved out of one with a nav bar, a command
// palette and four quick-add overlays, none of which have anywhere to go here --
// a standalone catalog that offered to add a task would be advertising a door
// that opens onto nothing.
export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}>
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
